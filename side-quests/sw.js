// Side Quests service worker: push notifications + offline copy (20.0).
// Pages and files of the app: network first (new versions load as before); if the network doesn't answer
// within 3s (plane Wi-Fi) or fails, the last saved copy opens. Data (Supabase) is never cached here: sq-db.js
// keeps it in IndexedDB. Kill switch: open the app with ?nosw=1 (clears this cache and unregisters).
var CACHE = "sq-app-v32"; // bump on every PRE change
var FONTS = "sq-fonts-v1";
// 20.1: the whole app is saved on install (all dashboards, scripts, images; ~2MB), so every dashboard opens offline.
// the list is generated by offline-list.py; anything else of the app is saved the first time it is opened.
var PRE = ["index.html", "abroad.html", "apple-touch-icon.png", "budget.html", "cars-market.js", "cars.html", "credit.html", "credit.js", "dash-back.css", "dash-lock.js", "dash-sub.js", "events.html", "expenses.html", "family.html", "fh-logo.png", "flags.js", "fold.js", "food-img/cottage-brownie.jpg", "food.html", "games.html", "housing.html", "icon-192.png", "icon-512.png", "img/art-cars.svg", "img/art-credit.svg", "img/art-expenses.svg", "img/art-family.svg", "img/art-food.svg", "img/art-housing.svg", "img/art-insurance.svg", "img/art-knowledge.svg", "img/art-payments.svg", "img/art-shopping.svg", "img/art-skills.svg", "img/art-sport.svg", "img/car-ford.jpg", "img/car-j8.jpg", "img/car-kia.jpg", "img/knowledge/field-rec-kit-overview.jpg", "img/knowledge/field-rec-kit-wiring.svg", "img/knowledge/mtg-rarity-guide.svg", "img/knowledge/svg.png", "img/nf-banner.webp", "img/stats-banner-900.webp", "img/stats-banner.webp", "income.html", "insurance.html", "israel.html", "knowledge.html", "logos.js", "manifest.json", "miluim.html", "nozoom.js", "payments.html", "personal-events.js", "proj-icons/cashflow.png", "proj-icons/cinema-city.png", "proj-icons/frame-horizon.png", "proj-icons/frida-app.png", "proj-icons/holiday-optimizer.png", "proj-icons/life-unfolded.png", "proj-icons/netflix-il.png", "proj-icons/personal-assistant.png", "proj-icons/sandwiches.png", "proj-icons/side-quests.png", "proj-icons/study.png", "rewards.html", "shopping.html", "skills.html", "sport.html", "sq-calm.js", "sq-db.js", "sq-fid.js", "sq-gfx.js", "sq-icons.js", "sq-tel.js", "sqctx.js", "timegate.js", "trip.html", "workcal-engine.js", "workcal.html"];
self.addEventListener("install", function (e) {
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then(function (ca) {
    return Promise.all(PRE.map(function (f) {
      var u = new URL(f, self.registration.scope).toString();
      return fetch(u, { cache: "no-cache" }).then(function (r) { if (r.ok) return ca.put(u, r); }).catch(function () {});
    }));
  }));
});
self.addEventListener("activate", function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k.indexOf("sq-") === 0 && k !== CACHE && k !== FONTS; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
function keyOf(req) {
  // one copy per file: drop the ?v= / ?u= cache-busting query (the page itself is saved without query or hash)
  var u = new URL(req.url); u.search = ""; u.hash = "";
  if (req.mode === "navigate" && /\/$/.test(u.pathname)) u.pathname += "index.html";
  return u.toString();
}
function netFirst(e) {
  var req = e.request, k = keyOf(req);
  var net = fetch(req).then(function (r) {
    if (r && r.ok && r.type === "basic") { var c = r.clone(); caches.open(CACHE).then(function (ca) { return ca.put(k, c); }); }
    return r;
  });
  var cached = function () { return caches.open(CACHE).then(function (ca) { return ca.match(k); }); };
  e.waitUntil(net.catch(function () {}));
  return new Promise(function (resolve, reject) {
    var done = false;
    var t = setTimeout(function () { cached().then(function (c) { if (c && !done) { done = true; resolve(c); } }); }, 3000);
    net.then(function (r) { if (!done) { done = true; clearTimeout(t); resolve(r); } }, function (err) {
      clearTimeout(t);
      cached().then(function (c) { if (done) return; done = true; if (c) resolve(c); else reject(err); });
    });
  });
}
function fontsCache(e) {
  return caches.open(FONTS).then(function (ca) {
    return ca.match(e.request).then(function (c) {
      var net = fetch(e.request).then(function (r) { if (r && (r.ok || r.type === "opaque")) ca.put(e.request, r.clone()); return r; });
      if (c) { e.waitUntil(net.catch(function () {})); return c; }
      return net;
    });
  });
}
// the app sends the local dashboard pages it knows (also new ones not in PRE yet) to be saved ahead of time
self.addEventListener("message", function (e) {
  var d = e.data || {};
  if (d.type !== "sq-warm" || !d.urls) return;
  e.waitUntil(caches.open(CACHE).then(function (ca) {
    return Promise.all(d.urls.map(function (raw) {
      try { var u = new URL(raw, self.registration.scope); u.search = ""; u.hash = ""; } catch (x) { return; }
      if (u.origin !== self.location.origin || u.pathname.indexOf(new URL(self.registration.scope).pathname) !== 0) return;
      var k = u.toString();
      return ca.match(k).then(function (hit) { if (hit) return; return fetch(k, { cache: "no-cache" }).then(function (r) { if (r.ok) return ca.put(k, r); }).catch(function () {}); });
    }));
  }));
});
self.addEventListener("fetch", function (e) {
  var req = e.request;
  if (req.method !== "GET") return;
  var u = new URL(req.url);
  if (u.origin === self.location.origin) {
    if (u.pathname.indexOf(new URL(self.registration.scope).pathname) !== 0) return;
    if (u.searchParams.has("nosw")) return;
    // the version check (?v=<time>, no-store) must really ask the network; offline it just fails quietly
    if (req.cache === "no-store") return;
    e.respondWith(netFirst(e));
  } else if (u.hostname === "fonts.googleapis.com" || u.hostname === "fonts.gstatic.com") {
    e.respondWith(fontsCache(e));
  }
});
self.addEventListener("push", function (e) {
  var d = {};
  try { d = e.data.json(); } catch (err) { d = { body: e.data ? e.data.text() : "" }; }
  e.waitUntil(self.registration.showNotification(d.title || "Side Quests", {
    body: d.body || "", icon: "icon-192.png", badge: "icon-192.png", tag: d.tag || "sq", lang: "he", dir: "rtl",
    data: { url: d.url || self.registration.scope }
  }));
});
self.addEventListener("notificationclick", function (e) {
  e.notification.close();
  var url = (e.notification.data && e.notification.data.url) || self.registration.scope;
  e.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(function (list) {
    for (var i = 0; i < list.length; i++) {
      var c = list[i];
      if (c.url.indexOf(self.registration.scope) === 0 && "focus" in c) {
        try { c.postMessage({ type: "sq-open", url: url }); } catch (x) {}
        return c.focus();
      }
    }
    return self.clients.openWindow(url);
  }));
});
